# ==========================================
# COMMON HELPERS
# ==========================================

def clean_filename(topic):
    filename = re.sub(r"[^a-zA-Z0-9_-]+", "_", topic)
    return filename.strip("_")[:60] or "Research_Report"


def parse_inline_markdown(text):
    """Convert basic Markdown formatting to ReportLab markup."""

    text = escape(text)

    # Bold
    text = re.sub(r"\*\*(.*?)\*\*", r"<b>\1</b>", text)

    # Italic
    text = re.sub(r"\*(.*?)\*", r"<i>\1</i>", text)

    # Inline code
    text = re.sub(
        r"`(.*?)`",
        r'<font name="Courier">\1</font>',
        text
    )

    # Clickable URLs
    text = re.sub(
        r"(https?://[^\s<]+)",
        r'<link href="\1" color="#6554C0">\1</link>',
        text
    )

    return text


# ==========================================
# WORD DOCUMENT GENERATOR
# ==========================================

def generate_word_report(topic, report):

    doc = Document()

    section = doc.sections[0]
    section.top_margin = Inches(0.75)
    section.bottom_margin = Inches(0.75)
    section.left_margin = Inches(0.85)
    section.right_margin = Inches(0.85)

    # Normal style
    normal = doc.styles["Normal"]
    normal.font.name = "Aptos"
    normal.font.size = Pt(10.5)
    normal.font.color.rgb = RGBColor(55, 65, 81)

    normal.paragraph_format.space_after = Pt(8)
    normal.paragraph_format.line_spacing = 1.3

    # Heading styles
    for style_name, size in [
        ("Heading 1", 19),
        ("Heading 2", 15),
        ("Heading 3", 12),
    ]:
        style = doc.styles[style_name]
        style.font.name = "Aptos Display"
        style.font.size = Pt(size)
        style.font.bold = True
        style.font.color.rgb = RGBColor(91, 72, 180)

    # Header
    header = section.header.paragraphs[0]
    header.text = "RESEARCHLAB  |  AI RESEARCH REPORT"
    header.alignment = WD_ALIGN_PARAGRAPH.RIGHT

    for run in header.runs:
        run.font.size = Pt(8)
        run.font.color.rgb = RGBColor(130, 130, 150)

    # Cover title
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title.paragraph_format.space_before = Pt(45)

    run = title.add_run("RESEARCH REPORT")
    run.bold = True
    run.font.size = Pt(12)
    run.font.color.rgb = RGBColor(120, 100, 210)

    topic_title = doc.add_paragraph()
    topic_title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    topic_title.paragraph_format.space_before = Pt(15)

    run = topic_title.add_run(topic)
    run.bold = True
    run.font.size = Pt(25)
    run.font.color.rgb = RGBColor(30, 40, 65)

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER

    run = subtitle.add_run("Generated by ResearchLab Multi-Agent AI System")
    run.font.size = Pt(10)
    run.font.color.rgb = RGBColor(120, 120, 140)

    date = doc.add_paragraph()
    date.alignment = WD_ALIGN_PARAGRAPH.CENTER

    run = date.add_run(
        "AI-powered research and analysis"
    )
    run.font.size = Pt(9)
    run.font.italic = True

    doc.add_paragraph()
    doc.add_page_break()

    # Report content
    for raw_line in report.splitlines():

        line = raw_line.strip()

        if not line:
            continue

        if line.startswith("# "):
            doc.add_heading(line[2:].strip(), level=1)

        elif line.startswith("## "):
            doc.add_heading(line[3:].strip(), level=2)

        elif line.startswith("### "):
            doc.add_heading(line[4:].strip(), level=3)

        elif line.startswith(("- ", "* ")):
            paragraph = doc.add_paragraph(style="List Bullet")
            paragraph.add_run(line[2:].strip())

        elif re.match(r"^\d+[\.\)]\s+", line):
            content = re.sub(r"^\d+[\.\)]\s+", "", line)
            paragraph = doc.add_paragraph(style="List Number")
            paragraph.add_run(content)

        elif line.startswith("> "):
            paragraph = doc.add_paragraph()
            paragraph.paragraph_format.left_indent = Inches(0.3)
            run = paragraph.add_run(line[2:])
            run.italic = True
            run.font.color.rgb = RGBColor(100, 100, 120)

        else:
            doc.add_paragraph(line)

    # Footer with page number
    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER

    run = footer.add_run("ResearchLab  •  Page ")
    run.font.size = Pt(8)
    run.font.color.rgb = RGBColor(120, 120, 140)

    field = OxmlElement("w:fldSimple")
    field.set(qn("w:instr"), "PAGE")
    footer._p.append(field)

    # Save in memory
    output = BytesIO()
    doc.save(output)
    output.seek(0)

    return output


# ==========================================
# PDF DOCUMENT GENERATOR
# ==========================================

def generate_pdf_report(topic, report):

    output = BytesIO()

    doc = SimpleDocTemplate(
        output,
        pagesize=A4,
        rightMargin=55,
        leftMargin=55,
        topMargin=65,
        bottomMargin=55,
        title=f"Research Report - {topic}",
        author="ResearchLab",
    )

    styles = getSampleStyleSheet()

    styles.add(ParagraphStyle(
        name="CoverTitle",
        parent=styles["Title"],
        fontSize=25,
        leading=32,
        textColor=colors.HexColor("#27314F"),
        alignment=TA_CENTER,
        spaceAfter=18,
    ))

    styles.add(ParagraphStyle(
        name="CoverSubtitle",
        parent=styles["Normal"],
        fontSize=10,
        textColor=colors.HexColor("#77778A"),
        alignment=TA_CENTER,
        leading=16,
    ))

    styles.add(ParagraphStyle(
        name="SectionHeading",
        parent=styles["Heading1"],
        fontSize=17,
        leading=23,
        textColor=colors.HexColor("#6554C0"),
        spaceBefore=17,
        spaceAfter=10,
        keepWithNext=True,
    ))

    styles.add(ParagraphStyle(
        name="SubHeading",
        parent=styles["Heading2"],
        fontSize=13,
        leading=18,
        textColor=colors.HexColor("#35415E"),
        spaceBefore=12,
        spaceAfter=7,
        keepWithNext=True,
    ))

    styles.add(ParagraphStyle(
        name="ReportBody",
        parent=styles["BodyText"],
        fontSize=9.5,
        leading=15,
        textColor=colors.HexColor("#374151"),
        spaceAfter=9,
    ))

    story = []

    # Cover
    story.append(Spacer(1, 1.4 * inch))

    story.append(Paragraph(
        "RESEARCHLAB",
        styles["CoverSubtitle"]
    ))

    story.append(Spacer(1, 0.3 * inch))

    story.append(Paragraph(
        "RESEARCH REPORT",
        styles["CoverTitle"]
    ))

    story.append(Paragraph(
        parse_inline_markdown(topic),
        styles["CoverSubtitle"]
    ))

    story.append(Spacer(1, 0.2 * inch))

    story.append(HRFlowable(
        width="45%",
        thickness=2,
        color=colors.HexColor("#6554C0"),
        hAlign="CENTER"
    ))

    story.append(Spacer(1, 0.3 * inch))

    story.append(Paragraph(
        "Generated by the Multi-Agent AI Research System",
        styles["CoverSubtitle"]
    ))

    story.append(PageBreak())

    # Main report
    for raw_line in report.splitlines():

        line = raw_line.strip()

        if not line:
            story.append(Spacer(1, 5))
            continue

        if line.startswith("# "):
            story.append(Paragraph(
                parse_inline_markdown(line[2:]),
                styles["SectionHeading"]
            ))

        elif line.startswith("## "):
            story.append(Paragraph(
                parse_inline_markdown(line[3:]),
                styles["SubHeading"]
            ))

        elif line.startswith("### "):
            story.append(Paragraph(
                parse_inline_markdown(line[4:]),
                styles["Heading3"]
            ))

        elif line.startswith(("- ", "* ")):
            story.append(Paragraph(
                "&#8226;&nbsp;&nbsp;" +
                parse_inline_markdown(line[2:]),
                styles["ReportBody"]
            ))

        elif re.match(r"^\d+[\.\)]\s+", line):
            story.append(Paragraph(
                parse_inline_markdown(line),
                styles["ReportBody"]
            ))

        elif line.startswith("> "):
            story.append(Paragraph(
                "<i>" + parse_inline_markdown(line[2:]) + "</i>",
                styles["ReportBody"]
            ))

        else:
            story.append(Paragraph(
                parse_inline_markdown(line),
                styles["ReportBody"]
            ))

    # Page header and footer
    def add_page_details(canvas, document):

        canvas.saveState()

        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.HexColor("#888899"))

        canvas.drawString(
            55,
            A4[1] - 38,
            "RESEARCHLAB  |  AI RESEARCH REPORT"
        )

        canvas.drawRightString(
            A4[0] - 55,
            30,
            f"Page {document.page}"
        )

        canvas.restoreState()

    doc.build(
        story,
        onFirstPage=add_page_details,
        onLaterPages=add_page_details
    )

    output.seek(0)

    return output
